@app.post('/api/users')
@require('users','create')
def users_create():
    d=request.get_json(silent=True) or {}; username=str(d.get('username','')).strip(); password=str(d.get('password','')); scope=d.get('scope','all'); perms=d.get('permissions',{})
    if len(username)<3 or len(password)<12 or scope not in SCOPES or not isinstance(perms,dict): return jsonify(error='invalid_user_data'),422
    if any(k not in MODULES or not isinstance(v,dict) or any(a not in ACTIONS for a in v) for k,v in perms.items()): return jsonify(error='invalid_permissions'),422
    try:
        with engine.begin() as c: c.execute(text('INSERT INTO users(username,display_name,password_hash,scope,active,is_owner,permissions,created_at) VALUES(:u,:n,:p,:s,TRUE,FALSE,:r,:t)'),{'u':username,'n':str(d.get('display_name') or username),'p':generate_password_hash(password),'s':scope,'r':json.dumps(perms),'t':datetime.now(timezone.utc).isoformat()})
    except IntegrityError: return jsonify(error='username_exists'),409
    log('user_created',username); return jsonify(ok=True),201
@app.patch('/api/users/<int:uid>')
@require('users','edit')
def users_edit(uid):
    d=request.get_json(silent=True) or {}
    with engine.begin() as c:
        row=c.execute(text('SELECT is_owner FROM users WHERE id=:i'),{'i':uid}).first()
        if not row: return jsonify(error='not_found'),404
        if row[0]: return jsonify(error='owner_protected'),403
        fields=[]; vals={'i':uid}
        for key,col in [('display_name','display_name'),('scope','scope'),('active','active'),('permissions','permissions'),('password','password_hash')]:
            if key in d:
                val=d[key]
                if key=='scope' and val not in SCOPES: return jsonify(error='invalid_scope'),422
                if key=='permissions':
                    if not isinstance(val,dict) or any(k not in MODULES for k in val): return jsonify(error='invalid_permissions'),422
                    val=json.dumps(val)
                if key=='password':
                    if len(str(val))<12: return jsonify(error='password_min_12'),422
                    val=generate_password_hash(str(val))
                if key=='active': val=bool(val)
                fields.append(f'{col}=:{key}'); vals[key]=val
        if fields: c.execute(text('UPDATE users SET '+','.join(fields)+' WHERE id=:i'),vals)
    log('user_updated',str(uid)); return jsonify(ok=True)
