def home(): return render_template('index.html', modules=MODULES, actions=ACTIONS, scopes=SCOPES)
@app.get('/api/setup-status')
def setup_status():
    with engine.connect() as c: n=c.execute(text('SELECT COUNT(*) FROM users WHERE is_owner=TRUE')).scalar_one()
    return jsonify(owner_exists=bool(n))
@app.post('/api/setup-owner')
def setup_owner():
    data=request.get_json(silent=True) or {}; setup_key=os.environ.get('OWNER_SETUP_KEY')
    if not setup_key or not secrets.compare_digest(str(data.get('setup_key','')),setup_key): return jsonify(error='invalid_setup_key'),403
    username=str(data.get('username','')).strip(); password=str(data.get('password',''))
    if len(username)<3 or len(password)<12: return jsonify(error='username_min_3_password_min_12'),422
    with engine.begin() as c:
        if c.execute(text('SELECT COUNT(*) FROM users WHERE is_owner=TRUE')).scalar_one(): return jsonify(error='owner_already_exists'),409
        c.execute(text('INSERT INTO users(username,display_name,password_hash,scope,active,is_owner,permissions,created_at) VALUES(:u,:n,:p,\'all\',TRUE,TRUE,\'{}\',:t)'),{'u':username,'n':str(data.get('display_name') or 'Owner'),'p':generate_password_hash(password),'t':datetime.now(timezone.utc).isoformat()})
    return jsonify(ok=True),201
@app.post('/api/login')
def login():
    d=request.get_json(silent=True) or {}; u=str(d.get('username','')).strip()
    with engine.connect() as c: row=c.execute(text('SELECT * FROM users WHERE username=:u AND active=TRUE'),{'u':u}).mappings().first()
    if not row or not check_password_hash(row['password_hash'],str(d.get('password',''))): return jsonify(error='invalid_credentials'),401
    session.clear(); session['uid']=row['id']; session['username']=row['username']; session.permanent=True
    log('login','successful'); return jsonify(ok=True,username=row['username'],owner=bool(row['is_owner']))
@app.post('/api/logout')
def logout():
    if session.get('uid'): log('logout')
    session.clear(); return jsonify(ok=True)
