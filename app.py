import os, secrets, json
from datetime import datetime, timedelta, timezone
from functools import wraps
from flask import Flask, request, jsonify, session, render_template, abort
from werkzeug.security import generate_password_hash, check_password_hash
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

app = Flask(__name__)
app.secret_key = os.environ.get('SECRET_KEY') or secrets.token_hex(32)
app.config.update(SESSION_COOKIE_HTTPONLY=True, SESSION_COOKIE_SAMESITE='Lax', SESSION_COOKIE_SECURE=os.environ.get('COOKIE_SECURE','1')=='1', PERMANENT_SESSION_LIFETIME=timedelta(hours=8), MAX_CONTENT_LENGTH=2*1024*1024)
DB_URL = os.environ.get('DATABASE_URL','sqlite:///./trial.sqlite3')
if DB_URL.startswith('postgres://'): DB_URL = DB_URL.replace('postgres://','postgresql+psycopg://',1)
elif DB_URL.startswith('postgresql://'): DB_URL = DB_URL.replace('postgresql://','postgresql+psycopg://',1)
engine = create_engine(DB_URL, pool_pre_ping=True)
MODULES=['dashboard','inventory','count','receiving','issuing','transfers','consumption','sales','purchases','employees','payroll','expenses','pl','recipes','users','settings']
ACTIONS=['view','create','edit','delete','approve','print','export']
SCOPES=['all','shatby','saba_pasha','warehouse']

def init_db():
    with engine.begin() as c:
        c.execute(text('''CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, username VARCHAR(80) UNIQUE NOT NULL, display_name VARCHAR(160) NOT NULL, password_hash TEXT NOT NULL, scope VARCHAR(30) NOT NULL DEFAULT 'all', active BOOLEAN NOT NULL DEFAULT TRUE, is_owner BOOLEAN NOT NULL DEFAULT FALSE, permissions TEXT NOT NULL DEFAULT '{}', created_at VARCHAR(40) NOT NULL)''') if engine.dialect.name=='postgresql' else text('''CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY AUTOINCREMENT, username TEXT UNIQUE NOT NULL, display_name TEXT NOT NULL, password_hash TEXT NOT NULL, scope TEXT NOT NULL DEFAULT 'all', active INTEGER NOT NULL DEFAULT 1, is_owner INTEGER NOT NULL DEFAULT 0, permissions TEXT NOT NULL DEFAULT '{}', created_at TEXT NOT NULL)'''))
        c.execute(text('''CREATE TABLE IF NOT EXISTS audit_log (id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, username VARCHAR(80) NOT NULL, action VARCHAR(100) NOT NULL, detail TEXT, created_at VARCHAR(40) NOT NULL)''') if engine.dialect.name=='postgresql' else text('''CREATE TABLE IF NOT EXISTS audit_log (id INTEGER PRIMARY KEY AUTOINCREMENT, username TEXT NOT NULL, action TEXT NOT NULL, detail TEXT, created_at TEXT NOT NULL)'''))

def log(action, detail=''):
    with engine.begin() as c: c.execute(text('INSERT INTO audit_log(username,action,detail,created_at) VALUES(:u,:a,:d,:t)'), {'u':session.get('username','system'),'a':action,'d':detail[:500],'t':datetime.now(timezone.utc).isoformat()})

def current_user():
    if not session.get('uid'): return None
    with engine.connect() as c: row=c.execute(text('SELECT * FROM users WHERE id=:i AND active=TRUE'),{'i':session['uid']}).mappings().first()
    return row

def need_login(fn):
    @wraps(fn)
    def w(*a,**k):
        if not current_user(): return jsonify(error='login_required'),401
        return fn(*a,**k)
    return w

def allowed(module, action):
    u=current_user()
    if not u: return False
    if u['is_owner']: return True
    try: p=json.loads(u['permissions'] or '{}')
    except: return False
    return bool(p.get(module,{}).get(action,False))

def require(module, action):
    def deco(fn):
        @wraps(fn)
        def w(*a,**k):
            if not current_user(): return jsonify(error='login_required'),401
            if not allowed(module,action): return jsonify(error='permission_denied'),403
            return fn(*a,**k)
        return w
    return deco

